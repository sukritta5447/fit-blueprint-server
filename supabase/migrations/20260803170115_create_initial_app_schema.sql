create or replace function private.refresh_post_likes_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected_post_id bigint := coalesce(new.post_id, old.post_id);
begin
  update public.posts
  set likes_count = (
    select count(*)::integer
    from public.post_likes
    where post_id = affected_post_id
  )
  where id = affected_post_id;

  return coalesce(new, old);
end;
$$;

revoke execute on function private.refresh_post_likes_count() from public;

create trigger refresh_post_likes_count
after insert or delete on public.post_likes
for each row execute function private.refresh_post_likes_count();

