create or replace function private.sync_auth_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_role text := coalesce(new.raw_app_meta_data ->> 'role', 'member');
  requested_status text := coalesce(
    new.raw_app_meta_data ->> 'account_status',
    'active'
  );
begin
  if requested_role not in (
    'member',
    'content_admin',
    'support_admin',
    'super_admin'
  ) then
    requested_role := 'member';
  end if;

  if requested_status not in ('active', 'paused', 'disabled') then
    requested_status := 'active';
  end if;

  insert into public.profiles (
    id,
    email,
    full_name,
    username,
    avatar_url,
    role,
    status
  )
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(btrim(new.raw_user_meta_data ->> 'username'), ''),
    nullif(btrim(new.raw_user_meta_data ->> 'avatar_url'), ''),
    requested_role,
    requested_status
  )
  on conflict (id) do update
  set
    email = excluded.email,
    role = excluded.role,
    status = excluded.status,
    updated_at = now();

  return new;
end;
$$;

revoke execute on function private.sync_auth_user_profile() from public;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.sync_auth_user_profile();

create trigger on_auth_user_access_changed
after update of email, raw_app_meta_data on auth.users
for each row execute function private.sync_auth_user_profile();

create or replace function private.current_user_is_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce(
    (select auth.jwt() -> 'app_metadata' ->> 'role') in (
      'content_admin',
      'support_admin',
      'super_admin'
    ),
    false
  );
$$;

create or replace function private.current_user_is_content_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce(
    (select auth.jwt() -> 'app_metadata' ->> 'role') in (
      'content_admin',
      'super_admin'
    ),
    false
  );
$$;

